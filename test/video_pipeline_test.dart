// video → map pipeline tests.
//
// Proves the two halves of the desktop dev surface against REAL externals:
//   1. VideoFrameExtractor over an ffmpeg-generated clip yields a BOUNDED stream
//      of exact, fixed-size RGBA frames (no codec in Dart, no unbounded buffer).
//   2. driveFrame pushes each extracted frame across the SAME FFI surface the
//      APK ships (native/build/libcarty_bridge.so): the frame provably reaches
//      `carty_infer_map_update`, which SAFE-FAILS ENOMODEL when the bridge has no
//      loadable weights (the model path passed to loadModel does not exist, so the
//      resident engine load failed) — no crash, no map mutation. This is the
//      task's verify criterion: "a frame stream reaches the FFI bridge without
//      crashing the main isolate."
//
// driveFrame runs the Geometric→Semantic FUSION (carty_ortho_project ->
// carty_infer_map_update_ortho), and the host `libcarty_bridge.so` now holds the
// Gemma engine RESIDENT and decodes IN-PROCESS (Route 1 — no subprocess). So when
// CARTY_GEMMA_MODEL points at the real .litertlm weights, loadModel loads them and
// the same call runs a REAL, slow grid-conditioned Gemma decode instead of
// safe-failing ENOMODEL. The ENOMODEL assertions below therefore only hold when no
// real model is configured; they are SKIPPED when it is, and a single opt-in
// real-decode test (CARTY_RUN_LITERT_DART=1) exercises the live path.
import 'dart:ffi';
import 'dart:io';
import 'dart:typed_data';

import 'package:carty/carty.dart';
import 'package:carty/carty_bindings_generated.dart' show CARTY_INFER_ENOMODEL;
import 'package:carty/inference/prompt.dart' show kMapUpdateSchemaContract;
import 'package:carty/vc.dart';
import 'package:carty/video.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  late Directory tmp;
  late String videoPath;

  setUpAll(() async {
    tmp = Directory.systemTemp.createTempSync('carty_vid_test_');
    videoPath = '${tmp.path}/sample.mp4';
    // A deterministic 3s test pattern at 64x64, 10fps — generated by the global
    // ffmpeg. lavfi needs no input file.
    final r = await Process.run('ffmpeg', [
      '-y', '-loglevel', 'error',
      '-f', 'lavfi',
      '-i', 'testsrc=duration=3:size=64x64:rate=10',
      '-pix_fmt', 'yuv420p',
      videoPath,
    ]);
    if (r.exitCode != 0) {
      fail('ffmpeg sample generation failed (is ffmpeg on PATH?): ${r.stderr}');
    }
  });

  tearDownAll(() {
    tmp.deleteSync(recursive: true);
  });

  group('VideoFrameExtractor (ffmpeg-backed)', () {
    test('probe reports the stream geometry', () async {
      final info = await const FfmpegVideoFrameExtractor().probe(videoPath);
      expect(info.width, equals(64));
      expect(info.height, equals(64));
      expect(info.frameRate, greaterThan(0));
    });

    test('extract yields bounded, exact-size, sequentially-indexed frames',
        () async {
      final frames = await const FfmpegVideoFrameExtractor()
          .extract(videoPath,
              targetWidth: 32, targetHeight: 32, sampleFps: 2, maxFrames: 5)
          .toList();

      expect(frames, isNotEmpty);
      expect(frames.length, lessThanOrEqualTo(5)); // bounded by construction
      for (final f in frames) {
        expect(f.width, equals(32));
        expect(f.height, equals(32));
        expect(f.channels, equals(kExtractChannels));
        expect(f.rgba.length, equals(32 * 32 * kExtractChannels)); // exact frame
      }
      expect(
        frames.map((f) => f.index).toList(),
        equals(List<int>.generate(frames.length, (i) => i)),
      );
    });

    test('maxFrames is a hard ceiling even on a longer clip', () async {
      final frames = await const FfmpegVideoFrameExtractor()
          .extract(videoPath,
              targetWidth: 16, targetHeight: 16, sampleFps: 10, maxFrames: 3)
          .toList();
      expect(frames.length, equals(3));
    });

    test('a missing file fails safely (no crash)', () {
      expect(
        () => const FfmpegVideoFrameExtractor().probe('/no/such/file.mp4'),
        throwsA(isA<VideoExtractionException>()),
      );
    });
  });

  // Will the in-process bridge actually decode? Only when CARTY_GEMMA_MODEL points
  // at real, loadable weights — then loadModel holds the engine resident and
  // driveFrame runs a REAL, slow decode, so the ENOMODEL contract no longer applies.
  // (Route 1 is in-process: there is NO separate runtime binary / CARTY_LITERT_RUNTIME.)
  final gemmaModelPath = Platform.environment['CARTY_GEMMA_MODEL'];
  final litertConfigured =
      gemmaModelPath != null && File(gemmaModelPath).existsSync();
  // The path handed to loadModel: the real weights when configured, else a bogus
  // path whose resident-engine load fails → decode safe-fails ENOMODEL (the
  // contract the gated tests below assert).
  final modelPath = litertConfigured ? gemmaModelPath : '/tmp/gemma4_e2b.litertlm';
  // Opt-in switch for the (multi-minute) live grid-conditioned decode.
  final runRealDecode = Platform.environment['CARTY_RUN_LITERT_DART'] == '1';

  final enomodelSkip = litertConfigured
      ? 'CARTY_GEMMA_MODEL points at real weights: driveFrame now runs a real '
          'in-process grid-conditioned decode, not ENOMODEL — see the opt-in '
          'CARTY_RUN_LITERT_DART real-decode test'
      : null;

  group(
      'driveFrame — frames reach the ortho fusion, safe-fail without crashing',
      () {
    late Carty carty;
    late CartyModelHandle model;

    setUpAll(() {
      final so = File('native/build/libcarty_bridge.so').absolute.path;
      if (!File(so).existsSync()) {
        fail('Build the host bridge first: cmake --build native/build ($so)');
      }
      carty = Carty.fromLibrary(DynamicLibrary.open(so));
      model = carty.loadModel(modelPath);
    });

    tearDownAll(() {
      model.dispose();
    });

    test(
      'an extracted clip folds through carty_infer_map_update_ortho (ENOMODEL)',
      () async {
        final frames = await const FfmpegVideoFrameExtractor()
            .extract(videoPath,
                targetWidth: 48, targetHeight: 48, sampleFps: 2, maxFrames: 4)
            .toList();
        expect(frames, isNotEmpty);

        var graph = MapGraph.empty();
        for (final frame in frames) {
          final result = driveFrame(
            carty: carty,
            model: model,
            frame: frame,
            base: graph,
            instruction: 'reconstruct the map region',
          );
          // The frame reached the bridge: orthorectified, then the grid-
          // conditioned inference safe-failed ENOMODEL (no loadable weights, so
          // the resident engine is null). The graph is left untouched — no crash,
          // no fabrication.
          expect(result.status, equals(CARTY_INFER_ENOMODEL));
          expect(result.applied, isFalse);
          graph = result.graph;
        }
        expect(graph.nodeCount, equals(0));
      },
      skip: enomodelSkip,
    );

    test(
      'driveFrame allocs+frees the bridge frame AND ortho grid (no leak)',
      () {
        // A synthetic zero frame exercises the same FFI alloc/zero-copy-write/
        // ortho-project/dispose path the extracted clip uses, sans ffmpeg.
        final frame = ExtractedFrame(
          index: 0,
          width: 8,
          height: 8,
          channels: kExtractChannels,
          rgba: Uint8List(8 * 8 * kExtractChannels),
        );
        final res = driveFrame(
          carty: carty,
          model: model,
          frame: frame,
          base: MapGraph.empty(),
          instruction: 'x',
        );
        expect(res.status, equals(CARTY_INFER_ENOMODEL));
        expect(res.graph.nodeCount, equals(0));
      },
      skip: enomodelSkip,
    );

    test(
      'a frame projects to a top-down ortho grid (geometric stage)',
      () {
        // The GEOMETRIC stage is deterministic and runtime-independent: it runs
        // identically whether or not LiteRT is configured, so it is NOT gated.
        final frame = ExtractedFrame(
          index: 0,
          width: 16,
          height: 16,
          channels: kExtractChannels,
          rgba: Uint8List(16 * 16 * kExtractChannels)..fillRange(0, 64, 200),
        );
        final buffer = carty.allocFrame(width: 16, height: 16, channels: 4);
        buffer.bytes.setAll(0, frame.rgba);
        final ortho = carty.orthoProject(buffer,
            width: 16, height: 16, channels: 4);
        try {
          expect(ortho.width, greaterThan(0));
          expect(ortho.height, greaterThan(0));
          expect(ortho.sizeInBytes, equals(ortho.width * ortho.height));
          // The native Spatial Context serializer is bounded + non-empty and
          // frames the Dart-owned contract (kMapUpdateSchemaContract) it is given.
          final prompt =
              ortho.spatialPrompt(instruction: kMapUpdateSchemaContract);
          // The prompt MUST carry the strict {"ops":[...]} contract the
          // authoritative Dart parser requires — NOT GeoJSON (no "ops" key).
          expect(prompt, contains('"ops"'));
        } finally {
          ortho.dispose();
          buffer.dispose();
        }
      },
    );

    test(
      'ortho fusion runs a REAL grid-conditioned Gemma decode (opt-in, slow)',
      () async {
        final frames = await const FfmpegVideoFrameExtractor()
            .extract(videoPath,
                targetWidth: 64, targetHeight: 64, sampleFps: 1, maxFrames: 1)
            .toList();
        expect(frames, isNotEmpty);

        final result = driveFrame(
          carty: carty,
          model: model,
          frame: frames.first,
          base: MapGraph.empty(),
          instruction: 'reconstruct the overhead map region',
        );
        // The whole Dart->ortho->Gemma->gate->parse path executed without
        // crashing the FFI boundary. A real decode either applied a valid update
        // (status >= 0, native gate + strict parser both accepted the GeoJSON)
        // or safe-failed (negative status, graph untouched) — never a crash.
        if (result.status >= 0) {
          expect(result.applied, isTrue);
          expect(result.graph.nodeCount, greaterThanOrEqualTo(0));
        } else {
          expect(result.graph.nodeCount, equals(0));
        }
        expect(result.note, isNotEmpty);
      },
      skip: runRealDecode
          ? false
          : 'set CARTY_RUN_LITERT_DART=1 (with CARTY_GEMMA_MODEL pointing at the '
              'real weights) to run the real multi-minute in-process Gemma decode',
      timeout: const Timeout(Duration(minutes: 8)),
    );
  });
}
